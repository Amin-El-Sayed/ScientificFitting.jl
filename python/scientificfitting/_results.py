"""Named Python snapshots; statistical decisions and scan extraction stay in Julia."""

from dataclasses import dataclass, field
from collections.abc import Mapping
from types import MappingProxyType

import numpy as np

from ._inputs import _snapshot
from ._runtime import _backend


@dataclass(frozen=True)
class DiagnosticFinding:
    """Core finding with a stable code, concrete evidence, and recommended action."""

    severity: str
    code: str
    title: str
    evidence: str
    recommendation: str


@dataclass(frozen=True)
class DiagnosticReport:
    """Full core diagnosis and its dashboard, without parsing printed text.

    Status is "ok", "review", or "stop"; "ok" only means that current checks
    found no warning or critical issue. It does not validate the physical model.
    Text fields are generated by Julia from these same findings.
    """

    findings: tuple[DiagnosticFinding, ...]
    summary: str
    status: str
    severity_counts: Mapping
    next_actions: tuple[str, ...]
    text: str
    dashboard_text: str

    def __str__(self):
        return self.dashboard_text


@dataclass(frozen=True)
class ParameterEstimate:
    """Named estimate; missing profile crossings remain NaN, not local errors."""

    name: str
    value: float
    uncertainty: float
    uncertainty_minus: float
    uncertainty_plus: float
    fixed: bool


@dataclass(frozen=True, eq=False)
class FitReport:
    """Extractable report; covariance remains local even with profile error bars."""

    parameters: Mapping
    statistics: Mapping
    covariance: np.ndarray
    correlation: np.ndarray
    backend: str
    converged: bool
    iterations: int | None
    message: str
    numerical_diagnostics: Mapping
    text: str

    def __str__(self):
        return self.text


@dataclass(frozen=True, eq=False)
class ProfileResult:
    """One-parameter profile with absolute costs and local-approximation diagnosis.

    The other free parameters were refitted at each value. Infinite costs mean
    failed refits; negative deltas can reveal a better minimum. Neither is hidden.
    """

    parameter: str
    values: np.ndarray
    cost_values: np.ndarray
    delta_cost: np.ndarray
    threshold: float
    best_value: float
    local_stderr: float
    diagnostics: DiagnosticReport
    _handle: object = field(repr=False)

    def interval(self):
        """Interpolate this scan's threshold crossings in Julia, without refitting.

        Unbracketed sides remain NaN. Coverage interpretations of thresholds
        require the usual likelihood-ratio assumptions.
        """
        return _interval(_backend().profile_interval(self._handle), self)


@dataclass(frozen=True, eq=False)
class ProfileInterval:
    """Asymmetric interval and its actual scan; unavailable endpoints are NaN."""

    parameter: str
    lower: float
    upper: float
    uncertainty_minus: float
    uncertainty_plus: float
    threshold: float
    profile_result: ProfileResult


@dataclass(frozen=True, eq=False)
class ContourResult:
    """Two-parameter scan. delta_cost[i,j] belongs to x[i], y[j].

    Use delta_cost.T with Matplotlib contourf. best_values and local_covariance
    describe the quadratic comparison, not another refit or a posterior sample.
    """

    parameters: tuple[str, str]
    x: np.ndarray
    y: np.ndarray
    cost_values: np.ndarray
    delta_cost: np.ndarray
    levels: np.ndarray
    best_values: np.ndarray
    local_covariance: np.ndarray
    diagnostics: DiagnosticReport


@dataclass(frozen=True)
class ProfileMatrixPanelTriage:
    """Panel diagnosis in core severity order; parameters identify the x/y axes."""

    parameters: tuple[str, str]
    status: str
    severity_counts: Mapping
    finding_codes: tuple[str, ...]
    next_action: str


@dataclass(frozen=True, eq=False)
class ProfileMatrixResult:
    """Completed scans keyed by parameter names, ready to plot without refitting.

    parameters preserves selection order. A contour key (x_name, y_name) names
    its axes; it is not a pair of matrix row/column indices. Diagonal panel keys
    repeat the same name. All array snapshots and mappings are read-only.
    """

    parameters: tuple[str, ...]
    best_values: np.ndarray
    local_stderr: np.ndarray
    local_covariance: np.ndarray
    local_correlation: np.ndarray
    profiles: Mapping
    contours: Mapping
    panel_status: Mapping
    diagnostics: DiagnosticReport
    _triage: tuple[ProfileMatrixPanelTriage, ...] = field(repr=False)

    def triage(self, *, include_ok=False):
        """Return the core's severity-ordered panel actions, without new scans."""
        return tuple(row for row in self._triage if include_ok or row.status != "ok")


def _diagnostic(data):
    values = dict(data)
    values["findings"] = tuple(DiagnosticFinding(**dict(f)) for f in values["findings"])
    values["next_actions"] = tuple(values["next_actions"])
    values["severity_counts"] = MappingProxyType(dict(values["severity_counts"]))
    return DiagnosticReport(**values)


def _numerical_diagnostics(data):
    values = dict(data)
    values["warnings"] = tuple(values["warnings"])
    values["active_bounds"] = tuple(values["active_bounds"])
    values["findings"] = tuple(DiagnosticFinding(**dict(f)) for f in values["findings"])
    return MappingProxyType(values)


def _fit_report(handle, names, sigdigits):
    data = dict(_backend().report_values(handle, names, sigdigits))
    data["parameters"] = MappingProxyType({
        item["name"]: ParameterEstimate(**dict(item)) for item in data["parameters"]})
    data["statistics"] = MappingProxyType(dict(data["statistics"]))
    for name in ("covariance", "correlation"):
        data[name] = _snapshot(data[name])
    data["numerical_diagnostics"] = _numerical_diagnostics(data["numerical_diagnostics"])
    return FitReport(**data)


def _profile(handle, name, sigma, diagnostics=None):
    diagnosis = diagnostics if diagnostics is not None else _backend().profile_diagnostics(handle, sigma)
    return ProfileResult(name, _snapshot(handle.values), _snapshot(handle.cost_values),
        _snapshot(handle.delta_cost), float(handle.threshold), float(handle.best_value),
        float(sigma), _diagnostic(diagnosis), handle)


def _interval(handle, profile):
    return ProfileInterval(profile.parameter, float(handle.lower), float(handle.upper),
        float(handle.uncertainty_minus), float(handle.uncertainty_plus),
        float(handle.threshold), profile)


def _contour(handle, names, center, covariance, diagnostics=None):
    diagnosis = diagnostics if diagnostics is not None else _backend().contour_diagnostics(handle, center, covariance)
    return ContourResult(tuple(names), _snapshot(handle.x_values), _snapshot(handle.y_values),
        _snapshot(handle.cost_values), _snapshot(handle.delta_cost), _snapshot(handle.levels),
        _snapshot(center), _snapshot(covariance), _diagnostic(diagnosis))


def _profile_matrix(handle):
    data = _backend().matrix_values(handle)
    names = tuple(data["parameters"])
    best, sigma, cov, corr = (_snapshot(data[key]) for key in
        ("best_values", "local_stderr", "local_covariance", "local_correlation"))
    positions = {name: i for i, name in enumerate(names)}
    profiles = {name: _profile(scan, name, sigma[positions[name]], report)
                for name, scan, report in data["profiles"]}
    contours = {}
    for first, second, scan, report in data["contours"]:
        indices = [positions[first], positions[second]]
        contours[first, second] = _contour(scan, (first, second), best[indices],
                                         cov[np.ix_(indices, indices)], report)
    triage = tuple(ProfileMatrixPanelTriage(tuple(row["parameters"]), row["status"],
        MappingProxyType(dict(row["severity_counts"])), tuple(row["finding_codes"]),
        row["next_action"]) for row in data["triage"])
    return ProfileMatrixResult(names, best, sigma, cov, corr, MappingProxyType(profiles),
        MappingProxyType(contours), MappingProxyType(dict(data["panel_status"])),
        _diagnostic(data["diagnostics"]), triage)
