# Misra1a: y = b1*(1-exp[-b2*x])
misra1a(x, p) = @. p[1] * (1 - exp(-p[2] * x))

# Chwirut2: y = exp(-b1*x)/(b2+b3*x)
chwirut2(x, p) = @. exp(-p[1] * x) / (p[2] + p[3] * x)

# Gauss1: y = b1*exp(-b2*x) + b3*exp(-(x-b4)**2/b5**2) + b6*exp(-(x-b7)**2/b8**2)
gauss1(x, p) = @. p[1] * exp(-p[2] * x) + p[3] * exp(-(x - p[4])^2 / p[5]^2) + p[6] * exp(-(x - p[7])^2 / p[8]^2)

# MGH17: y = b1 + b2*exp[-x*b4] + b3*exp[-x*b5]
mgh17(x, p) = @. p[1] + p[2] * exp(-x * p[4]) + p[3] * exp(-x * p[5])

# Rat42: y = b1 / (1+exp[b2-b3*x])
rat42(x, p) = @. p[1] / (1 + exp(p[2] - p[3] * x))

# Thurber: y = (b1 + b2*x + b3*x**2 + b4*x**3) / (1 + b5*x + b6*x**2 + b7*x**3)
thurber(x, p) = @. (p[1] + p[2] * x + p[3] * x^2 + p[4] * x^3) / (1 + p[5] * x + p[6] * x^2 + p[7] * x^3)

# BoxBOD: y = b1*(1-exp[-b2*x])
boxbod(x, p) = @. p[1] * (1 - exp(-p[2] * x))

# Eckerle4: y = (b1/b2) * exp[-0.5*((x-b3)/b2)**2]
eckerle4(x, p) = @. (p[1] / p[2]) * exp(-0.5 * ((x - p[3]) / p[2])^2)

